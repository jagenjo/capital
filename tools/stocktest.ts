import { createGame, addCompany, applyAction, processTurn, DEFAULT_SETTINGS, netWorth, equity, treasury } from '../shared/engine.js';
const s = createGame({ ...DEFAULT_SETTINGS, seed: 13, aiCompanies: 3, startCash: 2_000_000, targetNetWorth: 0 });
const me = addCompany(s, { name: 'Me', playerId: 'm' }), you = addCompany(s, { name: 'You', playerId: 'y' });
const ai = s.companies[0];
const A = (c: any, a: any) => { const x = applyAction(s, c.id, a) as any; console.log(c.name, a.type, a.company ?? '', a.qty ?? '', x.error ? 'ERR ' + x.error : 'ok'); return x; };
console.log('start price', ai.price, 'float', ai.float, 'nw me', netWorth(s, me));
const cash0 = me.cash; A(me, { type: 'buyShares', company: ai.id, qty: 100_000 }); console.log('paid', cash0 - me.cash, 'ai price now', ai.price, 'nw me', netWorth(s, me), '(spread cost', cash0 - netWorth(s, me) - 0, ')');
A(me, { type: 'buyShares', company: ai.id, qty: 500_000 });
A(me, { type: 'buyShares', company: me.id, qty: 10 });
A(me, { type: 'issueShares', qty: 600_000 }); A(me, { type: 'issueShares', qty: 300_000 });
console.log('me cash', me.cash, 'price', me.price, 'treasury', treasury(s, me), 'float', me.float, 'nw', netWorth(s, me), 'equity', equity(s, me));
A(you, { type: 'buyShares', company: me.id, qty: 100_000 });
A(me, { type: 'setPolicy', dividend: 50, invest: 30, target: 'facilities' });
A(me, { type: 'setPolicy', dividend: 80, invest: 30, target: 'facilities' });
const tiles = [...s.world!.tiles].map((ch, i) => ch === 'g' ? i : -1).filter(i => i >= 0);
A(me, { type: 'build', idx: tiles[40], btype: 'factory', product: 'bread' });
for (let i = 0; i < 11; i++) processTurn(s);
me.history.forEach(p => p.profit = 100000);
processTurn(s);
console.log('after year: me', me.news.slice(-3).map(n => n.text), 'ai price', ai.price, 'my price', me.price, 'you cash', you.cash);
console.log('world news', s.news.filter(n => n.tag === 'market').map(n => n.text));
